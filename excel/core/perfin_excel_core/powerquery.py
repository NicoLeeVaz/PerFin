"""Generate the Power Query (M) text in excel/core/powerquery from the contract.

    python3 -m perfin_excel_core powerquery --out excel/core/powerquery

Every query is read-only and local: File.Contents / Folder.Files under
<data root>\\reports, Excel.CurrentWorkbook is not used (the data root is a parameter
query, set by PerFin_Refresh from the Settings sheet), and the optional Access reader
uses Access.Database on a local file. No Web.Contents, OData, SharePoint or other
online source. A test checks that the committed files equal this output.
"""
from pathlib import Path

from . import spec

HEADER = ("// PerFin core shell (task 2c). GENERATED by perfin_excel_core.powerquery from\n"
          "// contracts/schemas/report_tables.json; edit the generator, not this file.\n"
          "// Read-only, local-only: refresh never writes back to any source.\n")

PARAM_DATA_ROOT = HEADER + """// Parameter: PerFin data root. PerFin_Refresh (VBA) writes the Settings value here.
// Blank in the template, so an unconfigured workbook fails visibly.
"" meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = false]
"""

PARAM_STALE_DAYS = HEADER + """// Parameter: a source older than this many days is STALE. Set from Settings by PerFin_Refresh.
%d meta [IsParameterQuery = true, Type = "Number", IsParameterQueryRequired = true]
""" % spec.DEFAULT_STALE_DAYS

FN_ROOT = HEADER + """// fnPerFinRoot: the validated local data root (no UNC/network path, no URL).
() as text =>
let
    Raw = if PerFinDataRoot = null then "" else Text.Trim(PerFinDataRoot),
    Root = Text.TrimEnd(Raw, "\\"),
    Lower = Text.Lower(Root),
    Checked =
        if Root = "" then error Error.Record("PerFin.NotConfigured", "data root is not set (Settings sheet)")
        else if Text.StartsWith(Root, "\\\\") or Text.StartsWith(Root, "//") then
            error Error.Record("PerFin.NonLocalPath", "data root must be a local folder, not a network path")
        else if Text.Contains(Lower, "://") or Text.StartsWith(Lower, "http") then
            error Error.Record("PerFin.NonLocalPath", "data root must be a local folder, not a URL")
        else if Text.Length(Root) < 3 or Text.Middle(Root, 1, 2) <> ":\\" then
            error Error.Record("PerFin.NonLocalPath", "data root must be an absolute local path such as C:\\...")
        else Root
in
    Checked
"""

FN_PARSE = HEADER + """// fnPerFinParse: convert one contract CSV field (text) to its typed value.
// Empty field = null. id/text/enum/currency/decimal_string stay text (never evaluated).
(raw as nullable text, colType as text, nullable as logical) as any =>
let
    Fail = (reason as text) => error Error.Record("PerFin.InvalidValue", reason),
    Digits = (t as text) as logical => Text.Length(t) > 0 and Text.Remove(t, {"0".."9"}) = "",
    Value =
        if raw = null or raw = "" then
            (if nullable then null else Fail("empty field in non-nullable column"))
        else if colType = "money_minor" or colType = "integer" then
            (if Digits(if Text.StartsWith(raw, "-") then Text.Middle(raw, 1) else raw) then
                let n = Int64.From(raw, "en-US") in
                    if colType = "money_minor" and Number.Abs(n) > 922337203685477
                    then Fail("outside the contract money bound") else n
             else Fail("not an integer"))
        else if colType = "boolean" then
            (if raw = "TRUE" then true else if raw = "FALSE" then false
             else Fail("boolean must be TRUE or FALSE"))
        else if colType = "date" then
            (if Text.Length(raw) = 10 and Text.Middle(raw, 4, 1) = "-" and Text.Middle(raw, 7, 1) = "-"
                and Digits(Text.Start(raw, 4)) and Digits(Text.Middle(raw, 5, 2)) and Digits(Text.End(raw, 2))
             then #date(Number.FromText(Text.Start(raw, 4), "en-US"), Number.FromText(Text.Middle(raw, 5, 2), "en-US"),
                        Number.FromText(Text.End(raw, 2), "en-US"))
             else Fail("date must be YYYY-MM-DD"))
        else if colType = "decimal_string" then
            (let parts = Text.Split(raw, ".") in
                if List.Count(parts) <= 2 and List.AllTrue(List.Transform(parts, Digits)) then raw
                else Fail("not a decimal string"))
        else raw
in
    Value
"""

FN_READ_CSV = HEADER + """// fnPerFinReadCsv: read <data root>\\reports\\<fileName> in the contract CSV dialect.
// Fails the whole query (never loads partial rows) on a byte order mark, a header that
// differs from the contract, an extra field, or any value that breaks its column type.
(fileName as text, columns as list) as table =>
let
    Names = List.Transform(columns, each _{0}),
    Path = fnPerFinRoot() & "\\reports\\" & fileName,
    Bytes = File.Contents(Path),
    HasBom = Binary.Length(Bytes) >= 3 and Binary.Range(Bytes, 0, 3) = #binary({239, 187, 191}),
    Csv = Csv.Document(Bytes, [Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv,
                               Columns = List.Count(Names) + 1]),
    Header = if Table.RowCount(Csv) = 0 then {} else List.FirstN(Record.FieldValues(Csv{0}), List.Count(Names)),
    Extra = Table.Column(Csv, "Column" & Text.From(List.Count(Names) + 1)),
    Checked =
        if HasBom then error Error.Record("PerFin.Invalid", fileName & ": UTF-8 byte order mark is not allowed")
        else if Header <> Names then error Error.Record("PerFin.BadHeader", fileName & ": header does not match the contract")
        else if List.NonNullCount(Extra) > 0 then error Error.Record("PerFin.Invalid", fileName & ": a row has extra fields")
        else Table.RemoveColumns(Table.Skip(Csv, 1), {"Column" & Text.From(List.Count(Names) + 1)}),
    Renamed = Table.RenameColumns(Checked, List.Zip({List.FirstN(Table.ColumnNames(Checked), List.Count(Names)), Names})),
    TypeOf = (t as text) as type =>
        if t = "money_minor" or t = "integer" then Int64.Type
        else if t = "date" then type date
        else if t = "boolean" then type logical
        else type text,
    Typed = Table.TransformColumns(Renamed,
        List.Transform(columns, (c) => {c{0}, (v) => fnPerFinParse(v, c{1}, c{2}), TypeOf(c{1})})),
    BadRows = Table.RowCount(Table.SelectRowsWithErrors(Typed)),
    Result =
        if BadRows > 0 then error Error.Record("PerFin.Invalid",
            fileName & ": " & Text.From(BadRows) & " row(s) break the contract types; nothing loaded")
        else Typed
in
    Result
"""

FN_READ_ACCESS = HEADER + """// OPTIONAL fnPerFinReadAccess: read a report table/query from the LOCAL Access back end
// (<data root>\\db\\PerFin.accdb) with the Access connector. Not installed by default; use it
// only after task 2b confirms the Access object names, and keep the contract checks of
// fnPerFinReadCsv (types, nulls, header) when switching a query to it.
(objectName as text) as table =>
let
    Db = Access.Database(File.Contents(fnPerFinRoot() & "\\db\\PerFin.accdb"), [CreateNavigationProperties = false]),
    Data = Db{[Schema = "", Item = objectName]}[Data]
in
    Data
"""

ACCOUNTS_CHECK = """    Bad = Table.SelectRows(Source, each ([kind] <> "asset" and [kind] <> "liability")
        or [display_balance_minor] <> (if [kind] = "liability" then -[ledger_balance_minor] else [ledger_balance_minor])),
    Result = if Table.RowCount(Bad) > 0 then error Error.Record("PerFin.Invalid",
        "rpt_accounts.csv: display_balance_minor must equal the ledger balance (assets) or minus it (liabilities)")
        else Source
in
    Result
"""


def _col_list(table, indent="        "):
    rows = []
    for name, col_type, nullable in spec.columns(table):
        rows.append('%s{"%s", "%s", %s}' % (indent, name, col_type, "true" if nullable else "false"))
    return "{\n" + ",\n".join(rows) + "\n    }"


def _source_query(table, file_name, note):
    body = "    Source = fnPerFinReadCsv(\"%s\", %s)" % (file_name, _col_list(table))
    if table == "rpt_accounts":
        return HEADER + note + "let\n" + body + ",\n" + ACCOUNTS_CHECK
    return HEADER + note + "let\n" + body + "\nin\n    Source\n"


def _m_type(col_type, nullable):
    t = {"money_minor": "Int64.Type", "integer": "Int64.Type", "date": "date", "datetime": "datetime",
         "boolean": "logical"}.get(col_type, "text")
    return ("nullable " + t) if nullable else t


def _table_type(table):
    return "type table [\n" + ",\n".join(
        "        %s = %s" % (n, _m_type(t, nl)) for n, t, nl in spec.columns(table)) + "\n    ]"


def _status_query():
    sources = ",\n".join('        {"%s", %s}' % (s, '"%s"' % spec.AS_OF_COLUMN[s] if s in spec.AS_OF_COLUMN else "null")
                         for s in spec.CORE_SOURCES)
    record = ", ".join("%s = %s" % (s, s) for s in spec.CORE_SOURCES)
    return HEADER + """// perfin_refresh_status: one row per core report source. Refreshed LAST by PerFin_Refresh.
// Only OK counts as current. A missing, invalid or stale source is listed here and the
// banner on every sheet turns red, so old data is never presented as a fresh success.
let
    Now = DateTime.LocalNow(),
    Days = PerFinStaleDays,
    Horizon = Now - #duration(Days, 0, 0, 0),
    Files = try Folder.Files(fnPerFinRoot() & "\\reports") otherwise null,
    Tables = [%s],
    Sources = {
%s
    },
    Check = (src as list) as record =>
        let
            Name = src{0},
            FileName = Name & ".csv",
            Meta = if Files = null then null else Table.SelectRows(Files, each [Name] = FileName),
            Modified = if Meta = null or Table.RowCount(Meta) = 0 then null else Meta{0}[Date modified],
            Loaded = try Record.Field(Tables, Name),
            Reason = if Loaded[HasError] then Loaded[Error][Reason] else null,
            Rows = if Loaded[HasError] then null else Table.RowCount(Loaded[Value]),
            AsOf = if Loaded[HasError] or src{1} = null or Rows = 0 then null
                   else List.Max(Table.Column(Loaded[Value], src{1})),
            StaleFile = Modified <> null and Modified < Horizon,
            StaleData = AsOf <> null and AsOf < Date.From(Horizon),
            Status =
                if not Loaded[HasError] then (if StaleFile or StaleData then "STALE" else "OK")
                else if Reason = "PerFin.BadHeader" then "BAD_HEADER"
                else if Modified = null then "MISSING"
                else "INVALID",
            Message =
                if Loaded[HasError] then
                    (if Text.StartsWith(Reason, "PerFin.") then Loaded[Error][Message]
                     else if Modified = null then "file not found in <data root>\\reports"
                     else "could not read the file (" & Reason & ")")
                else if StaleFile and StaleData then "file and data as-of older than " & Text.From(Days) & " days"
                else if StaleFile then "file older than " & Text.From(Days) & " days"
                else if StaleData then "data as of more than " & Text.From(Days) & " days before refresh"
                else null
        in
            [source = Name, file_name = FileName, status = Status, row_count = Rows, file_modified = Modified,
             data_as_of = AsOf, checked_at = Now, message = Message],
    Result = Table.FromRecords(List.Transform(Sources, Check), %s)
in
    Result
""" % (record, sources, _table_type(spec.STATUS_TABLE))


def _recon_query():
    return HEADER + """// perfin_statement_recon: statements with opening/closing balances (ledger and display sign),
// their reconciliation status and the unreconciled transactions inside each period.
// Same rules as perfin_excel_core.reports.derive_views (tested on Linux).
let
    Kinds = Table.SelectColumns(rpt_accounts, {"account_id", "kind"}),
    Open = Table.SelectRows(rpt_transactions, each [reconciled] = false),
    PickRec = (sid as text) as nullable record =>
        let
            // Rule (same as reports.derive_views): a balanced reconciliation wins over
            // in_progress; ties go to the highest reconciliation_id. Table.Sort gets column
            // criteria only, so the priority is a temporary numeric column.
            Rows = Table.SelectRows(rpt_reconciliation, each [statement_id] = sid),
            Ranked = Table.AddColumn(Rows, "__perfin_priority",
                each if [recon_status] = "balanced" then 0 else 1, Int64.Type),
            Sorted = Table.Sort(Ranked, {{"__perfin_priority", Order.Ascending},
                                         {"reconciliation_id", Order.Descending}}),
            Best = Table.RemoveColumns(Table.FirstN(Sorted, 1), {"__perfin_priority"})
        in
            if Table.RowCount(Best) = 0 then null else Best{0},
    Statements = Table.Sort(rpt_statements, {{"account_id", Order.Ascending}, {"period_end", Order.Ascending},
                                             {"statement_id", Order.Ascending}}),
    Rows = Table.TransformRows(Statements, (s) =>
        let
            K = Table.SelectRows(Kinds, each [account_id] = s[account_id]),
            Kind = if Table.RowCount(K) = 0 then null else K{0}[kind],
            Sign = if Kind = "asset" then 1 else if Kind = "liability" then -1 else null,
            Items = Table.SelectRows(Open, each [account_id] = s[account_id]
                and [posted_date] >= s[period_start] and [posted_date] <= s[period_end]),
            Rec = PickRec(s[statement_id]),
            Sum = List.Sum(Table.Column(Items, "amount_minor"))
        in
            [statement_id = s[statement_id], account_id = s[account_id], account_kind = Kind,
             period_start = s[period_start], period_end = s[period_end], due_date = s[due_date],
             opening_balance_minor = s[opening_balance_minor], closing_balance_minor = s[closing_balance_minor],
             opening_display_minor = if Sign = null then null else Sign * s[opening_balance_minor],
             closing_display_minor = if Sign = null then null else Sign * s[closing_balance_minor],
             reconciliation_id = if Rec = null then null else Rec[reconciliation_id],
             recon_status = if Rec = null then "%s" else Rec[recon_status],
             included_count = if Rec = null then null else Rec[included_count],
             difference_minor = if Rec = null then null else Rec[difference_minor],
             unreconciled_count = Table.RowCount(Items),
             unreconciled_minor = if Sum = null then 0 else Sum]),
    Result = Table.FromRecords(Rows, %s)
in
    Result
""" % (spec.NOT_RECONCILED, _table_type("perfin_statement_recon"))


def _items_query():
    return HEADER + """// perfin_unreconciled_items: transactions inside a statement period that no balanced
// reconciliation includes (rpt_transactions[reconciled] = FALSE).
let
    Open = Table.SelectRows(rpt_transactions, each [reconciled] = false),
    Statements = Table.Sort(rpt_statements, {{"account_id", Order.Ascending}, {"period_end", Order.Ascending},
                                             {"statement_id", Order.Ascending}}),
    PerStatement = Table.TransformRows(Statements, (s) =>
        let
            Items = Table.Sort(Table.SelectRows(Open, each [account_id] = s[account_id]
                and [posted_date] >= s[period_start] and [posted_date] <= s[period_end]),
                {{"posted_date", Order.Ascending}, {"transaction_id", Order.Ascending}})
        in
            Table.TransformRows(Items, (t) => [statement_id = s[statement_id], account_id = t[account_id],
                transaction_id = t[transaction_id], posted_date = t[posted_date],
                amount_minor = t[amount_minor], description = t[description]])),
    Result = Table.FromRecords(List.Combine(PerStatement), %s)
in
    Result
""" % _table_type("perfin_unreconciled_items")


def queries():
    """{file name: M text}, plus the load manifest (query name, load target)."""
    out = {
        "PerFinDataRoot.pq": PARAM_DATA_ROOT,
        "PerFinStaleDays.pq": PARAM_STALE_DAYS,
        "fnPerFinRoot.pq": FN_ROOT,
        "fnPerFinParse.pq": FN_PARSE,
        "fnPerFinReadCsv.pq": FN_READ_CSV,
        "optional/fnPerFinReadAccess.pq": FN_READ_ACCESS,
    }
    manifest = [("PerFinDataRoot", "connection"), ("PerFinStaleDays", "connection"), ("fnPerFinRoot", "connection"),
                ("fnPerFinParse", "connection"), ("fnPerFinReadCsv", "connection")]
    from .workbook import TABLE_PLACES
    for table in spec.CORE_SOURCES:
        note = "// %s: read-only refresh of <data root>\\reports\\%s.csv (contract %s).\n" % (
            table, table, "1.0.0")
        out[table + ".pq"] = _source_query(table, table + ".csv", note)
        manifest.append((table, "table" if table in TABLE_PLACES else "connection"))
    out["perfin_statement_recon.pq"] = _recon_query()
    out["perfin_unreconciled_items.pq"] = _items_query()
    out["perfin_modules.pq"] = _source_query(
        spec.MODULES_TABLE, spec.MODULES_CSV,
        "// perfin_modules: module registry written by `python -m perfin_excel_core registry` (read-only here).\n")
    out["perfin_refresh_status.pq"] = _status_query()
    manifest += [("perfin_statement_recon", "table"), ("perfin_unreconciled_items", "table"),
                 ("perfin_modules", "table"), ("perfin_refresh_status", "table")]
    out["queries.txt"] = ("# PerFin Power Query install order: <query name>|<table|connection>.\n"
                          "# 'table' queries load into the workbook table of the same name; refresh order is this order.\n"
                          + "".join("%s|%s\n" % m for m in manifest))
    return out


def write(out_dir):
    out_dir = Path(out_dir)
    for rel, text in queries().items():
        p = out_dir / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="ascii", newline="\r\n") as f:
            f.write(text)
    return sorted(queries())
